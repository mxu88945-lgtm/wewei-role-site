/**
 * v236 借鉴人的记忆：
 * - 线索触发（海马体索引）：每条记忆有一小串「线索」（人名、地点、物件、关键词、情绪），和本体分开。
 *   每轮只拿她最新一句 + 他上一条回复去对线索；对上了（或语义召回命中）才把本体拉进本轮背景。
 * - 用进废退：记下 lastRecalledAt / recallCount。排序 = 相关度 × 重要度 × 新鲜度；
 *   很久没被想起的慢慢变淡（最低 0.4 倍，永不删除），被想起一次就刷新，想起越多次忘得越慢。
 * - 重要的事更容易记住：承诺、纪念日、第一次、吵架与和好……基础重要度更高。
 * 纯函数，不调模型、不读存储。
 */
import type { PersonaMemoryEntry, PersonaMessage } from './personaWindow'

const DAY = 24 * 60 * 60 * 1000
export const MEMORY_CUE_MAX = 8
export const MEMORY_CUE_CHARS = 12
/** 被想起 0 次时的「半衰期」：30 天后权重衰减一半（再往后有 0.4 的下限）。 */
export const MEMORY_HALF_LIFE_DAYS = 30
export const MEMORY_FRESHNESS_FLOOR = 0.4

const normalized = (value: string) => value.toLocaleLowerCase().replace(/[\s\p{P}\p{S}]+/gu, '')

/** 重要事件：承诺/约定、纪念日/生日、第一次、冲突与和好、坦白/表白、生病住院、搬家换工作。 */
const IMPORTANT_EVENT = /承诺|约定|答应|说好|发誓|纪念日|生日|周年|第一次|初次|吵架|冷战|闹别扭|和好|道歉|原谅|表白|告白|坦白|分手|求婚|永远|住院|手术|生病|去世|离世|搬家|换工作|辞职|毕业|考试|面试/
const EMOTION = /哭|难过|伤心|委屈|生气|害怕|焦虑|孤单|想念|开心|幸福|感动|心疼|喜欢|爱/
const EMOTION_WORDS = ['哭', '难过', '伤心', '委屈', '生气', '害怕', '焦虑', '孤单', '想念', '开心', '感动', '心疼']

/** 1–5。存了就用存的（整理器给的）；旧数据按文字估：重要事件 4、带情绪 3、其余 2；她亲手写/确认的再 +1。 */
export function memoryImportance(entry: Pick<PersonaMemoryEntry, 'importance' | 'title' | 'content' | 'autoGenerated'>): number {
  const stored = Number(entry.importance)
  if (Number.isFinite(stored) && stored >= 1) return Math.min(5, Math.round(stored))
  const text = `${entry.title} ${entry.content}`
  const base = IMPORTANT_EVENT.test(text) ? 4 : EMOTION.test(text) ? 3 : 2
  return Math.min(5, base + (entry.autoGenerated ? 0 : 1))
}

/** 重要度 → 倍数：1 → 0.8 … 5 → 1.6。 */
export const importanceWeight = (importance: number) => 0.6 + 0.2 * Math.min(5, Math.max(1, importance))

/** 新鲜度：从最后一次「被写/被改/被想起」算起，按半衰期衰减；想起越多次半衰期越长。 */
export function memoryFreshness(entry: Pick<PersonaMemoryEntry, 'createdAt' | 'updatedAt' | 'lastRecalledAt' | 'recallCount'>, now = Date.now()) {
  const anchor = Math.max(entry.lastRecalledAt || 0, entry.updatedAt || 0, entry.createdAt || 0)
  if (!anchor || anchor >= now) return 1
  const halfLife = MEMORY_HALF_LIFE_DAYS * (1 + Math.min(10, Math.max(0, entry.recallCount || 0)) * 0.5)
  const decay = Math.pow(0.5, (now - anchor) / DAY / halfLife)
  return MEMORY_FRESHNESS_FLOOR + (1 - MEMORY_FRESHNESS_FLOOR) * decay
}

const cleanCue = (value: string) => value.replace(/[\s「」『』《》“”"'（）()【】[\]]/g, '').trim().slice(0, MEMORY_CUE_CHARS)

/** 整理器给的线索；没有就从标题、引号/书名号里的词和情绪词里取（旧数据兼容）。 */
export function memoryCues(entry: Pick<PersonaMemoryEntry, 'cues' | 'title' | 'content'>): string[] {
  const stored = (entry.cues || []).map(cleanCue).filter((cue) => cue.length >= 2)
  if (stored.length) return [...new Set(stored)].slice(0, MEMORY_CUE_MAX)
  const derived: string[] = []
  const title = entry.title.replace(/[·・]\d+$/, '')
  // 标题像一句话（[记忆:…] 存下的）就不当线索，太长对不上。
  if (title && title !== '记忆' && title !== '手写记忆') derived.push(...title.split(/[、，,/／\s·和与及]+/).filter((part) => part.length <= 8))
  for (const match of entry.content.matchAll(/[「『《“"]([^」』》”"\n]{2,12})[」』》”"]/g)) derived.push(match[1])
  derived.push(...EMOTION_WORDS.filter((word) => entry.content.includes(word)))
  return [...new Set(derived.map(cleanCue).filter((cue) => cue.length >= 2))].slice(0, MEMORY_CUE_MAX)
}

/** 本轮「线索扫描」文字：她最新一句 + 他上一条回复（只看这两条，不看整段历史）。 */
export function cueScanText(history: readonly PersonaMessage[]) {
  const usable = history.filter((message) => message.text.trim() && message.finishReason !== 'error')
  const lastUser = usable.map((message) => message.role).lastIndexOf('user')
  if (lastUser < 0) return ''
  const reply = usable.slice(0, lastUser).reverse().find((message) => message.role === 'assistant')
  return [reply?.text.slice(0, 600) || '', usable[lastUser].text.slice(0, 1200)].filter(Boolean).join('\n')
}

/** 线索命中个数（同义词组里的别名也算，例如 鹦鹉|小鸡）。 */
export function cueHits(cues: readonly string[], scan: string, aliasGroups: readonly string[][] = []) {
  const text = normalized(scan)
  if (!text) return 0
  return cues.filter((cue) => {
    const key = normalized(cue)
    if (key.length < 2) return false
    if (text.includes(key)) return true
    return aliasGroups.some((group) => group.some((alias) => key.includes(alias)) && group.some((alias) => text.includes(alias)))
  }).length
}

export type MemoryRankInput = {
  scan: string
  /** 语义召回命中（记忆 id → 余弦相似度）；不传 = 语义召回没开/失败，走线索 + 关键词。 */
  semantic?: ReadonlyMap<string, number>
  /** 旧的关键词打分（v139），语义召回不可用时作为兜底，要求够强。 */
  keywordScore?: (entry: PersonaMemoryEntry) => number
  aliasGroups?: readonly string[][]
  now?: number
}
export type RankedMemory = { entry: PersonaMemoryEntry; score: number; relevance: number; via: 'semantic' | 'cue' | 'keyword' }

/** 关键词兜底的门槛：至少两个三字词或四个两字词那么强，免得「晚上」「吃了」这种泛词把记忆都拉进来。 */
export const KEYWORD_FALLBACK_MIN = 4

export function rankPersonaMemories(entries: readonly PersonaMemoryEntry[], input: MemoryRankInput): RankedMemory[] {
  const now = input.now ?? Date.now()
  const rows: RankedMemory[] = []
  for (const entry of entries) {
    const semantic = input.semantic?.get(entry.id) || 0
    const cues = cueHits(memoryCues(entry), input.scan, input.aliasGroups)
    const keyword = !input.semantic && input.keywordScore ? input.keywordScore(entry) : 0
    // 语义：0.55 → 1、0.75 → 3；线索每个 2；关键词兜底只在够强时算。
    const semanticPart = semantic > 0 ? Math.max(0, (semantic - 0.45) * 10) : 0
    const relevance = semanticPart + cues * 2 + (keyword >= KEYWORD_FALLBACK_MIN ? keyword / 2 : 0)
    if (relevance <= 0) continue
    const via = semanticPart >= cues * 2 && semanticPart > 0 ? 'semantic' : cues ? 'cue' : 'keyword'
    rows.push({ entry, relevance, via, score: relevance * importanceWeight(memoryImportance(entry)) * memoryFreshness(entry, now) })
  }
  return rows.sort((a, b) => b.score - a.score || (b.entry.updatedAt || b.entry.createdAt) - (a.entry.updatedAt || a.entry.createdAt))
}

/** 再巩固：本轮真正带进去的记忆刷新一次（不改内容，所以不会动稳定前缀和向量索引）。 */
export function touchRecalledMemories(entries: PersonaMemoryEntry[], ids: readonly string[], now = Date.now()): PersonaMemoryEntry[] {
  if (!ids.length) return entries
  const wanted = new Set(ids)
  let changed = false
  const next = entries.map((entry) => {
    if (!wanted.has(entry.id)) return entry
    changed = true
    return { ...entry, lastRecalledAt: now, recallCount: (entry.recallCount || 0) + 1 }
  })
  return changed ? next : entries
}

/** 送去做向量的文字：线索 + 标题 + 本体（不含想起次数等会变的字段，免得反复重算）。 */
export function memorySemanticText(entry: Pick<PersonaMemoryEntry, 'cues' | 'title' | 'content'>) {
  const cues = memoryCues(entry)
  return `${cues.length ? `线索：${cues.join('、')}\n` : ''}${entry.title}：${entry.content.trim()}`.slice(0, 1200)
}

