const isRecord = (value: unknown): value is Record<string, unknown> => Boolean(value) && typeof value === 'object' && !Array.isArray(value)
const text = (value: unknown) => typeof value === 'string' ? value : ''

function normalizeMessage(value: unknown): PersonaMessage | null {
  if (!isRecord(value)) return null
  const id = Number(value.id)
  const role = value.role === 'user' ? 'user' : value.role === 'assistant' ? 'assistant' : null
  if (!Number.isFinite(id) || !role) return null
  const images = Array.isArray(value.images) ? (value.images as ChatImage[]).filter((image) => image && typeof image.dataUrl === 'string') : undefined
  const recallSources = (Array.isArray(value.recallSources) ? value.recallSources : []).filter(isRecord).filter((source) => text(source.threadId) && Number.isSafeInteger(source.messageId) && (source.role === 'user' || source.role === 'assistant')).slice(0, 20).map((source): PersonaRecallSource => ({ threadId: text(source.threadId), messageId: Number(source.messageId), title: text(source.title), role: source.role === 'user' ? 'user' : 'assistant', createdAt: Number(source.createdAt) || 0 }))
  return { id, role, text: text(value.text), createdAt: Number(value.createdAt) || 0, ...(images?.length ? { images } : {}), ...(value.finishReason !== undefined ? { finishReason: (value.finishReason as string | null) } : {}), ...(recallSources.length ? { recallSources } : {}), ...(role === 'assistant' && text(value.taskCompletionId) ? { taskCompletionId: text(value.taskCompletionId) } : {}) }
}

function normalizeMemory(value: unknown): PersonaMemoryEntry | null {
  if (!isRecord(value)) return null
  const content = text(value.content).trim()
  if (!content) return null
  return {
    id: text(value.id) || crypto.randomUUID(),
    title: text(value.title).trim() || '记忆',
    content,
    createdAt: Number(value.createdAt) || 0,
    ...(value.updatedAt ? { updatedAt: Number(value.updatedAt) || 0 } : {}),
    ...(value.pinned ? { pinned: true } : {}),
    ...(value.autoGenerated ? { autoGenerated: true } : {}),
    ...(value.locked ? { locked: true } : {}),
    ...(text(value.sourceThreadId) ? { sourceThreadId: text(value.sourceThreadId) } : {}),
    ...(Array.isArray(value.sourceMessageIds) ? { sourceMessageIds: value.sourceMessageIds.filter((id): id is number => typeof id === 'number' && Number.isSafeInteger(id)) } : {}),
  }
}

const optionalId = (value: unknown) => value !== undefined && value !== null && Number.isFinite(Number(value)) ? Number(value) : undefined

function normalizeThread(raw: Record<string, unknown>, fallbackId: string, index: number): PersonaThread {
  const memoryThroughId = optionalId(raw.memoryThroughId)
  const compressedThroughId = optionalId(raw.compressedThroughId)
  return {
    id: text(raw.id) || fallbackId,
    title: text(raw.title).trim() || (index === 0 ? '窗口 1' : `窗口 ${index + 1}`),
    createdAt: Number(raw.createdAt) || 0,
    updatedAt: Number(raw.updatedAt) || 0,
    messages: (Array.isArray(raw.messages) ? raw.messages : []).map(normalizeMessage).filter((item): item is PersonaMessage => Boolean(item)),
    ...(memoryThroughId !== undefined ? { memoryThroughId } : {}),
    ...(text(raw.contextSummary) ? { contextSummary: text(raw.contextSummary) } : {}),
    ...(compressedThroughId !== undefined ? { compressedThroughId } : {}),
    ...(raw.summaryFallback ? { summaryFallback: true } : {}),
    ...(Number(raw.summaryUpdatedAt) ? { summaryUpdatedAt: Number(raw.summaryUpdatedAt) } : {}),
    ...(isRecord(raw.recallLedger) ? { recallLedger: Object.fromEntries(Object.entries(raw.recallLedger).filter(([, turn]) => typeof turn === 'number' && Number.isSafeInteger(turn) && turn >= 0).sort((a, b) => Number(b[1]) - Number(a[1])).slice(0, 120)) as Record<string, number> } : {}),
    ...(Number.isSafeInteger(Number(raw.messageSequence)) && Number(raw.messageSequence) > 0 ? { messageSequence: Number(raw.messageSequence) } : {}),
    ...(Array.isArray(raw.tasks) ? { tasks: normalizePersonaTasks(raw.tasks) } : {}),
  }
}

export const firstThreadIdFor = (personaId: string) => `${personaId}-w1`

/**
 * v1 kept one chat per persona (messages / memoryThroughId / contextSummary / compressedThroughId
 * on the persona itself). v2 moves them, unchanged, into the persona's first window.
 */
export function normalizePersonaState(value: unknown): PersonaWindowState {
  if (!isRecord(value) || !Array.isArray(value.personas)) return emptyPersonaState()
  const seen = new Set<string>()
  const personas: PersonaWindow[] = []
  for (const raw of value.personas) {
    if (!isRecord(raw)) continue
    const characterId = text(raw.characterId)
    if (!characterId) continue
    const id = text(raw.id) || personaIdFor(characterId)
    if (seen.has(id)) continue
    seen.add(id)
    const createdAt = Number(raw.createdAt) || 0
    const updatedAt = Number(raw.updatedAt) || 0
    const threadIds = new Set<string>()
    let threads = (Array.isArray(raw.threads) ? raw.threads : []).filter(isRecord).map((item, index) => normalizeThread(item, index === 0 ? firstThreadIdFor(id) : `${id}-w${index + 1}`, index))
      .filter((thread) => { if (threadIds.has(thread.id)) return false; threadIds.add(thread.id); return true })
    if (!threads.length) threads = [normalizeThread({ ...raw, id: firstThreadIdFor(id), title: '窗口 1', createdAt, updatedAt }, firstThreadIdFor(id), 0)]
    const activeThreadId = threads.some((thread) => thread.id === text(raw.activeThreadId)) ? text(raw.activeThreadId) : threads[0].id
    personas.push({
      id,
      characterId,
      createdAt,
      updatedAt,
      enabled: raw.enabled !== false,
      threads,
      activeThreadId,
      memories: (Array.isArray(raw.memories) ? raw.memories : []).map(normalizeMemory).filter((item): item is PersonaMemoryEntry => Boolean(item)),
      autoMemory: raw.autoMemory !== false,
      pastLifeEnabled: raw.pastLifeEnabled !== false,
      ...(text(raw.apiChannelId) ? { apiChannelId: text(raw.apiChannelId) } : {}),
      ...(text(raw.modelName).trim() ? { modelName: text(raw.modelName).trim() } : {}),
      ...(text(raw.systemPrompt).trim() ? { systemPrompt: text(raw.systemPrompt) } : {}),
      ...(raw.recallEnabled === false ? { recallEnabled: false } : {}),
      ...(raw.recallScope === 'thread' ? { recallScope: 'thread' } : {}),
      ...(text(raw.memoryAliases).trim() ? { memoryAliases: text(raw.memoryAliases).slice(0, 4000) } : {}),
      ...(normalizePersonaAppearance(raw.appearance) ? { appearance: normalizePersonaAppearance(raw.appearance) } : {}),
      ...(raw.tasksEnabled === false ? { tasksEnabled: false } : {}),
    })
  }
  const activeId = text(value.activeId)
  return { version: 2, activeId: personas.some((item) => item.id === activeId && item.enabled) ? activeId : personas.find((item) => item.enabled)?.id || '', personas }
}

export function createPersonaThread(personaId: string, index: number, now = Date.now(), id?: string): PersonaThread {
  return { id: id || (index === 0 ? firstThreadIdFor(personaId) : `${personaId}-${now.toString(36)}-${Math.random().toString(36).slice(2, 7)}`), title: `窗口 ${index + 1}`, createdAt: now, updatedAt: now, messages: [] }
}

export function createPersonaWindow(characterId: string, now = Date.now()): PersonaWindow {
  const id = personaIdFor(characterId)
  const thread = createPersonaThread(id, 0, now)
  return { id, characterId, createdAt: now, updatedAt: now, enabled: true, threads: [thread], activeThreadId: thread.id, memories: [], autoMemory: true, pastLifeEnabled: true }
}

/** The window being shown for a persona (falls back to its first). */
export function activeThread(persona: PersonaWindow, threadId?: string): PersonaThread {
  return persona.threads.find((item) => item.id === (threadId || persona.activeThreadId)) || persona.threads[0]
}

/** The window she talked in most recently (used by 小手机). */
export function latestThread(persona: PersonaWindow): PersonaThread | undefined {
  return persona.threads.slice().sort((a, b) => (b.updatedAt || 0) - (a.updatedAt || 0))[0]
}

export function updatePersonaThread(state: PersonaWindowState, personaId: string, threadId: string, transform: (thread: PersonaThread) => PersonaThread): PersonaWindowState {
  return updatePersona(state, personaId, (persona) => {
    let changed = false
    const threads = persona.threads.map((item) => {
      if (item.id !== threadId) return item
      changed = true
      return transform(item)
    })
    return changed ? { ...persona, threads } : persona
  })
}

export function addPersonaThread(state: PersonaWindowState, personaId: string, now = Date.now()): PersonaWindowState {
  return updatePersona(state, personaId, (persona) => {
    const used = new Set(persona.threads.map((item) => item.title))
    let index = persona.threads.length
    while (used.has(`窗口 ${index + 1}`)) index += 1
    const thread = { ...createPersonaThread(persona.id, Math.max(1, index), now), title: `窗口 ${index + 1}` }
    return { ...persona, threads: [...persona.threads, thread], activeThreadId: thread.id }
  })
}

export function switchPersonaThread(state: PersonaWindowState, personaId: string, threadId: string): PersonaWindowState {
  return updatePersona(state, personaId, (persona) => persona.threads.some((item) => item.id === threadId) ? { ...persona, activeThreadId: threadId } : persona)
}

export function renamePersonaThread(state: PersonaWindowState, personaId: string, threadId: string, title: string): PersonaWindowState {
  const next = title.trim().slice(0, 40)
  return next ? updatePersonaThread(state, personaId, threadId, (thread) => ({ ...thread, title: next })) : state
}

/** Delete one window's chat. The persona's memories stay; the last window is replaced by an empty one. */
export function deletePersonaThread(state: PersonaWindowState, personaId: string, threadId: string, now = Date.now()): PersonaWindowState {
  return updatePersona(state, personaId, (persona) => {
    if (!persona.threads.some((item) => item.id === threadId)) return persona
    const rest = persona.threads.filter((item) => item.id !== threadId)
    const threads = rest.length ? rest : [{ ...createPersonaThread(persona.id, 1, now), title: '窗口 1' }]
    const activeThreadId = persona.activeThreadId === threadId ? (latestThread({ ...persona, threads }) || threads[0]).id : persona.activeThreadId
    return { ...persona, threads, activeThreadId }
  })
}

/** Persona's chosen channel, or the main chat's when it follows the main chat (or its channel was deleted). */
export function resolvePersonaApi(persona: Pick<PersonaWindow, 'apiChannelId' | 'modelName'> | undefined, channels: ApiChannel[], mainApi: ApiChannel): ApiChannel {
  if (!persona?.apiChannelId) return mainApi
  if (!channels.some((item) => item.id === persona.apiChannelId)) return mainApi
  return resolveApiChannel(channels, mainApi, persona.apiChannelId, persona.modelName)
}

/** Memory: the dedicated memory API when it is configured, otherwise this persona's own chat channel. */
export function personaMemoryApi(selectedMemoryApi: ApiConfig, personaApi: ApiConfig): ApiConfig {
  if (isApiChannelComplete(selectedMemoryApi)) return selectedMemoryApi
  return isApiChannelComplete(personaApi) ? personaApi : selectedMemoryApi
}

/** Enable a character as a persona. A previously removed persona comes back with its own chat and memory intact. */
export function enablePersona(state: PersonaWindowState, characterId: string, now = Date.now()): PersonaWindowState {
  const existing = state.personas.find((item) => item.characterId === characterId)
  if (existing) {
    return { ...state, activeId: existing.id, personas: state.personas.map((item) => item.id === existing.id ? { ...item, enabled: true } : item) }
  }
  const persona = createPersonaWindow(characterId, now)
  return { ...state, activeId: persona.id, personas: [...state.personas, persona] }
}

/** Hide a persona from the window. Its chat and memory are kept for when it is added back. */
export function disablePersona(state: PersonaWindowState, personaId: string): PersonaWindowState {
  const personas = state.personas.map((item) => item.id === personaId ? { ...item, enabled: false } : item)
  const activeId = state.activeId === personaId ? personas.find((item) => item.enabled)?.id || '' : state.activeId
  return { ...state, activeId, personas }
}

/** Permanently delete one persona's chat and memory. Other personas are untouched. */
export function deletePersona(state: PersonaWindowState, personaId: string): PersonaWindowState {
  const personas = state.personas.filter((item) => item.id !== personaId)
  const activeId = state.activeId === personaId ? personas.find((item) => item.enabled)?.id || '' : state.activeId
  return { ...state, activeId, personas }
}

export function switchPersona(state: PersonaWindowState, personaId: string): PersonaWindowState {
  return state.personas.some((item) => item.id === personaId && item.enabled) ? { ...state, activeId: personaId } : state
}

export function updatePersona(state: PersonaWindowState, personaId: string, transform: (persona: PersonaWindow) => PersonaWindow): PersonaWindowState {
  let changed = false
  const personas = state.personas.map((item) => {
    if (item.id !== personaId) return item
    changed = true
    return transform(item)
  })
  return changed ? { ...state, personas } : state
}

export const nextPersonaMessageId = (messages: PersonaMessage[]) => messages.reduce((max, item) => Math.max(max, item.id), 0) + 1

/** Keep evidence IDs unique and invalidate a summary whose raw source was removed. */
export function deletePersonaMessage(state: PersonaWindowState, personaId: string, threadId: string, messageId: number) {
  return updatePersonaThread(state, personaId, threadId, (thread) => {
    if (!thread.messages.some((message) => message.id === messageId)) return thread
    const invalidates = thread.compressedThroughId !== undefined && messageId <= thread.compressedThroughId
    return {
      ...thread,
      messageSequence: Math.max(thread.messageSequence || 0, nextPersonaMessageId(thread.messages) - 1),
      messages: thread.messages.filter((message) => message.id !== messageId),
      tasks: thread.tasks?.filter((task) => task.sourceMessageId !== messageId),
      ...(invalidates ? { contextSummary: undefined, compressedThroughId: undefined, summaryFallback: undefined, summaryUpdatedAt: undefined } : {}),
    }
  })
}

/** Memory reads and writes are always keyed by persona id; nothing here can reach another persona. */
export function personaMemories(state: PersonaWindowState, personaId: string) {
  return state.personas.find((item) => item.id === personaId)?.memories || []
}

const normalizedMemoryText = (value: string) => value.toLocaleLowerCase().replace(/[\s，。！？；：、“”‘’"'（）()【】［］《》<>…,.!?;:/\\|·]/g, '')

export function mergePersonaMemories(existing: PersonaMemoryEntry[], incoming: PersonaMemoryEntry[], _limit = PERSONA_MEMORY_LIMIT) {
  const merged = existing.slice()
  for (const candidate of incoming) {
    const key = normalizedMemoryText(candidate.content)
    const titleKey = normalizedMemoryText(candidate.title)
    const index = merged.findIndex((item) => normalizedMemoryText(item.content) === key || (titleKey.length >= 4 && normalizedMemoryText(item.title) === titleKey))
    if (index < 0) { merged.push(candidate); continue }
    const previous = merged[index]
    // A hand-edited memory is hers: an automatic pass never overwrites it.
    if (previous.autoGenerated === true && !previous.locked && !previous.pinned && normalizedMemoryText(previous.content) !== key) merged[index] = { ...previous, content: candidate.content, title: candidate.title, updatedAt: candidate.createdAt, sourceThreadId: candidate.sourceThreadId, sourceMessageIds: candidate.sourceMessageIds }
  }
  // Bound the prompt, not durable storage: new automatic saves must never evict
  // an old hand-written or unpinned memory. Originals and memory rows stay local.
  return merged
}

/** Write auto-extracted memories into exactly one persona and advance only that window's cursor. */
export function applyPersonaMemoryExtraction(state: PersonaWindowState, personaId: string, incoming: PersonaMemoryEntry[], throughId: number, threadId?: string): PersonaWindowState {
  return updatePersona(state, personaId, (persona) => {
    const target = threadId ? persona.threads.find((thread) => thread.id === threadId) : activeThread(persona)
    if (!target) return persona
    return {
      ...persona,
      memories: mergePersonaMemories(persona.memories, incoming),
      threads: persona.threads.map((thread) => thread.id === target?.id ? { ...thread, memoryThroughId: Math.max(thread.memoryThroughId || 0, throughId) } : thread),
    }
  })
}

export function pendingPersonaMemoryMessages(thread: Pick<PersonaThread, 'messages' | 'memoryThroughId'>) {
  const through = thread.memoryThroughId || 0
  return thread.messages.filter((item) => item.id > through && item.text.trim() && !(item.role === 'assistant' && item.finishReason === 'error'))
}

export const pendingPersonaMemoryCount = (persona: PersonaWindow) => persona.threads.reduce((sum, thread) => sum + pendingPersonaMemoryMessages(thread).length, 0)

export function shouldExtractPersonaMemory(persona: PersonaWindow, thread: PersonaThread = activeThread(persona), every = PERSONA_MEMORY_EVERY) {
  return persona.autoMemory !== false && pendingPersonaMemoryMessages(thread).length >= every
}

