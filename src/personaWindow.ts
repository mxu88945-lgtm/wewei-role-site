import type { StoryProject } from './storyProject'
import { stripPresentationalHtmlForPrompt } from './regexEngine'
import type { ChatImage } from './chatImages'
import type { Conversation } from './conversationLifecycle'
import type { LongMemoryEntry, LongMemoryMap } from './memoryEngine'
import { stripUiOnlyStatusBlocks } from './modelContext'

export const PERSONA_WINDOWS_KEY = 'weijing.personaWindows'
/** 自动整理记忆：攒够这么多条新消息（用户 + 角色）就后台整理一次。 */
export const PERSONA_MEMORY_EVERY = 12
/** 单次整理最多读这么多条，剩下的留给下一次。 */
export const PERSONA_MEMORY_BATCH = 60
export const PERSONA_MEMORY_LIMIT = 300
export const PAST_LIFE_MAX_CHARS = 10000
const PAST_LIFE_PER_CONVERSATION = 2600

export type PersonaMessage = {
  id: number
  role: 'user' | 'assistant'
  text: string
  images?: ChatImage[]
  createdAt: number
  finishReason?: string | null
}

export type PersonaMemoryEntry = {
  id: string
  title: string
  content: string
  createdAt: number
  updatedAt?: number
  pinned?: boolean
  autoGenerated?: boolean
}

export type PersonaWindow = {
  /** 人格 id（记忆按它隔离），与 characterId 一一对应。 */
  id: string
  characterId: string
  createdAt: number
  updatedAt: number
  /** 移出窗口时只隐藏，不删除对话和记忆；重新加入即可恢复。 */
  enabled: boolean
  messages: PersonaMessage[]
  memories: PersonaMemoryEntry[]
  /** 已整理进长期记忆的最后一条消息 id。 */
  memoryThroughId?: number
  /** 自动整理记忆，默认开。 */
  autoMemory?: boolean
  /** 前世记忆（小手机 + 长剧情）只读注入，默认开。 */
  pastLifeEnabled?: boolean
  /** 较早对话的压缩摘要；只影响请求，不改原文。 */
  contextSummary?: string
  /** 摘要覆盖到的最后一条消息 id（用 id 而非下标，删消息也不会错位）。 */
  compressedThroughId?: number
}

export type PersonaWindowState = { version: 1; activeId: string; personas: PersonaWindow[] }

export const emptyPersonaState = (): PersonaWindowState => ({ version: 1, activeId: '', personas: [] })

export const personaIdFor = (characterId: string) => `persona-${characterId}`

const isRecord = (value: unknown): value is Record<string, unknown> => Boolean(value) && typeof value === 'object' && !Array.isArray(value)
const text = (value: unknown) => typeof value === 'string' ? value : ''

function normalizeMessage(value: unknown): PersonaMessage | null {
  if (!isRecord(value)) return null
  const id = Number(value.id)
  const role = value.role === 'user' ? 'user' : value.role === 'assistant' ? 'assistant' : null
  if (!Number.isFinite(id) || !role) return null
  const images = Array.isArray(value.images) ? (value.images as ChatImage[]).filter((image) => image && typeof image.dataUrl === 'string') : undefined
  return { id, role, text: text(value.text), createdAt: Number(value.createdAt) || 0, ...(images?.length ? { images } : {}), ...(value.finishReason !== undefined ? { finishReason: (value.finishReason as string | null) } : {}) }
}

function normalizeMemory(value: unknown): PersonaMemoryEntry | null {
  if (!isRecord(value)) return null
  const content = text(value.content).trim()
  if (!content) return null
  return {
    id: text(value.id) || crypto.randomUUID(),
    title: text(value.title).trim() || '记忆',
    content,
    createdAt: Number(value.createdAt) || 0,
    ...(value.updatedAt ? { updatedAt: Number(value.updatedAt) || 0 } : {}),
    ...(value.pinned ? { pinned: true } : {}),
    ...(value.autoGenerated ? { autoGenerated: true } : {}),
  }
}

export function normalizePersonaState(value: unknown): PersonaWindowState {
  if (!isRecord(value) || !Array.isArray(value.personas)) return emptyPersonaState()
  const seen = new Set<string>()
  const personas: PersonaWindow[] = []
  for (const raw of value.personas) {
    if (!isRecord(raw)) continue
    const characterId = text(raw.characterId)
    if (!characterId) continue
    const id = text(raw.id) || personaIdFor(characterId)
    if (seen.has(id)) continue
    seen.add(id)
    personas.push({
      id,
      characterId,
      createdAt: Number(raw.createdAt) || 0,
      updatedAt: Number(raw.updatedAt) || 0,
      enabled: raw.enabled !== false,
      messages: (Array.isArray(raw.messages) ? raw.messages : []).map(normalizeMessage).filter((item): item is PersonaMessage => Boolean(item)),
      memories: (Array.isArray(raw.memories) ? raw.memories : []).map(normalizeMemory).filter((item): item is PersonaMemoryEntry => Boolean(item)),
      ...(Number.isFinite(Number(raw.memoryThroughId)) && raw.memoryThroughId !== undefined ? { memoryThroughId: Number(raw.memoryThroughId) } : {}),
      autoMemory: raw.autoMemory !== false,
      pastLifeEnabled: raw.pastLifeEnabled !== false,
      ...(text(raw.contextSummary) ? { contextSummary: text(raw.contextSummary) } : {}),
      ...(Number.isFinite(Number(raw.compressedThroughId)) && raw.compressedThroughId !== undefined ? { compressedThroughId: Number(raw.compressedThroughId) } : {}),
    })
  }
  const activeId = text(value.activeId)
  return { version: 1, activeId: personas.some((item) => item.id === activeId && item.enabled) ? activeId : personas.find((item) => item.enabled)?.id || '', personas }
}

export function createPersonaWindow(characterId: string, now = Date.now()): PersonaWindow {
  return { id: personaIdFor(characterId), characterId, createdAt: now, updatedAt: now, enabled: true, messages: [], memories: [], autoMemory: true, pastLifeEnabled: true }
}

/** Enable a character as a persona. A previously removed persona comes back with its own chat and memory intact. */
export function enablePersona(state: PersonaWindowState, characterId: string, now = Date.now()): PersonaWindowState {
  const existing = state.personas.find((item) => item.characterId === characterId)
  if (existing) {
    return { ...state, activeId: existing.id, personas: state.personas.map((item) => item.id === existing.id ? { ...item, enabled: true } : item) }
  }
  const persona = createPersonaWindow(characterId, now)
  return { ...state, activeId: persona.id, personas: [...state.personas, persona] }
}

/** Hide a persona from the window. Its chat and memory are kept for when it is added back. */
export function disablePersona(state: PersonaWindowState, personaId: string): PersonaWindowState {
  const personas = state.personas.map((item) => item.id === personaId ? { ...item, enabled: false } : item)
  const activeId = state.activeId === personaId ? personas.find((item) => item.enabled)?.id || '' : state.activeId
  return { ...state, activeId, personas }
}

/** Permanently delete one persona's chat and memory. Other personas are untouched. */
export function deletePersona(state: PersonaWindowState, personaId: string): PersonaWindowState {
  const personas = state.personas.filter((item) => item.id !== personaId)
  const activeId = state.activeId === personaId ? personas.find((item) => item.enabled)?.id || '' : state.activeId
  return { ...state, activeId, personas }
}

export function switchPersona(state: PersonaWindowState, personaId: string): PersonaWindowState {
  return state.personas.some((item) => item.id === personaId && item.enabled) ? { ...state, activeId: personaId } : state
}

export function updatePersona(state: PersonaWindowState, personaId: string, transform: (persona: PersonaWindow) => PersonaWindow): PersonaWindowState {
  let changed = false
  const personas = state.personas.map((item) => {
    if (item.id !== personaId) return item
    changed = true
    return transform(item)
  })
  return changed ? { ...state, personas } : state
}

export const nextPersonaMessageId = (messages: PersonaMessage[]) => messages.reduce((max, item) => Math.max(max, item.id), 0) + 1

/** Memory reads and writes are always keyed by persona id; nothing here can reach another persona. */
export function personaMemories(state: PersonaWindowState, personaId: string) {
  return state.personas.find((item) => item.id === personaId)?.memories || []
}

const normalizedMemoryText = (value: string) => value.toLocaleLowerCase().replace(/[\s，。！？；：、“”‘’"'（）()【】［］《》<>…,.!?;:/\\|·]/g, '')

export function mergePersonaMemories(existing: PersonaMemoryEntry[], incoming: PersonaMemoryEntry[], limit = PERSONA_MEMORY_LIMIT) {
  const merged = existing.slice()
  for (const candidate of incoming) {
    const key = normalizedMemoryText(candidate.content)
    const titleKey = normalizedMemoryText(candidate.title)
    const index = merged.findIndex((item) => normalizedMemoryText(item.content) === key || (titleKey.length >= 4 && normalizedMemoryText(item.title) === titleKey))
    if (index < 0) { merged.push(candidate); continue }
    const previous = merged[index]
    // A hand-edited memory is hers: an automatic pass never overwrites it.
    if (previous.autoGenerated === true && normalizedMemoryText(previous.content) !== key) merged[index] = { ...previous, content: candidate.content, title: candidate.title, updatedAt: candidate.createdAt }
  }
  const pinned = merged.filter((item) => item.pinned)
  const ordinary = merged.filter((item) => !item.pinned)
  return [...pinned, ...ordinary.slice(-Math.max(0, limit - pinned.length))]
}

/** Write auto-extracted memories into exactly one persona and advance only its cursor. */
export function applyPersonaMemoryExtraction(state: PersonaWindowState, personaId: string, incoming: PersonaMemoryEntry[], throughId: number): PersonaWindowState {
  return updatePersona(state, personaId, (persona) => ({
    ...persona,
    memories: mergePersonaMemories(persona.memories, incoming),
    memoryThroughId: Math.max(persona.memoryThroughId || 0, throughId),
  }))
}

export function pendingPersonaMemoryMessages(persona: PersonaWindow) {
  const through = persona.memoryThroughId || 0
  return persona.messages.filter((item) => item.id > through && item.text.trim() && !(item.role === 'assistant' && item.finishReason === 'error'))
}

export function shouldExtractPersonaMemory(persona: PersonaWindow, every = PERSONA_MEMORY_EVERY) {
  return persona.autoMemory !== false && pendingPersonaMemoryMessages(persona).length >= every
}

export const personaMemoryExtractionPrompt = `【人格窗口长期记忆整理器｜只输出 JSON，不要续写对话】
你要从“本次新增对话”里，整理出值得 {{char}} 长期记住的内容。这是 {{char}} 与 {{user}} 在一个独立窗口里一对一相处的记忆，只属于这一扇窗口。

值得记：
- {{user}} 亲口说出的近况、经历、喜好、习惯、身体与情绪状况、重要的人和日子；
- 两人之间已经发生的约定、承诺、玩笑梗、称呼、关系里的重要时刻；
- {{char}} 在这里已经明确表达过的立场、决定和自我认知。

不要记：
- 普通寒暄、一次性的情绪和氛围描写；
- 猜测、推断、尚未确认的事，以及模型自己补写的内容；
- 已有记忆里已经写过的同一件事（除非有了新变化，写成更新后的完整版本）。

输出一个 JSON 对象，不要 Markdown 代码围栏、解释或其他文字：
{"memories":[{"title":"简短标题","content":"一两句话，写清楚是什么、何时、结果如何"}]}
没有值得记的内容时返回 {"memories":[]}。`

function jsonCandidates(raw: string) {
  const cleaned = raw.replace(/^\s*```(?:json)?\s*/i, '').replace(/\s*```\s*$/i, '').trim()
  const candidates = [cleaned]
  const start = cleaned.indexOf('{')
  const end = cleaned.lastIndexOf('}')
  if (start >= 0 && end > start) candidates.push(cleaned.slice(start, end + 1))
  const arrayStart = cleaned.indexOf('[')
  const arrayEnd = cleaned.lastIndexOf(']')
  if (arrayStart >= 0 && arrayEnd > arrayStart) candidates.push(cleaned.slice(arrayStart, arrayEnd + 1))
  return candidates
}

export function parsePersonaMemoryCandidates(raw: string, now = Date.now()): PersonaMemoryEntry[] | null {
  for (const candidate of jsonCandidates(raw)) {
    let parsed: unknown
    try { parsed = JSON.parse(candidate) } catch { continue }
    const items = Array.isArray(parsed) ? parsed : isRecord(parsed) && Array.isArray(parsed.memories) ? parsed.memories : null
    if (!items) continue
    const seen = new Set<string>()
    const entries: PersonaMemoryEntry[] = []
    for (const item of items) {
      if (!isRecord(item)) continue
      const content = stripUiOnlyStatusBlocks(text(item.content || item.summary || item.fact)).trim().slice(0, 1200)
      const title = text(item.title || item.name).trim().slice(0, 80) || content.slice(0, 16)
      const key = normalizedMemoryText(content)
      if (!content || seen.has(key)) continue
      seen.add(key)
      entries.push({ id: crypto.randomUUID(), title, content, createdAt: now, autoGenerated: true })
    }
    return entries
  }
  return null
}

/** Persona memories in the shape the shared prompt builder injects (relevance-picked, pinned always). */
export function personaMemoriesForPrompt(persona: PersonaWindow): LongMemoryEntry[] {
  return persona.memories.map((item) => ({ id: item.id, title: item.title, content: `【${item.title}】${item.content}`, pinned: item.pinned, createdAt: item.createdAt }))
}

export function personaCompressedUntil(persona: PersonaWindow) {
  if (!persona.contextSummary || persona.compressedThroughId === undefined) return 0
  const through = persona.compressedThroughId
  return persona.messages.filter((item) => item.id <= through).length
}

type PastLifeInput = {
  character: Pick<Character, 'id' | 'name'> & Partial<Character>
  conversations: readonly Conversation[]
  memoryEntries: Readonly<LongMemoryMap>
  /** All cards; cards with exactly the same name (duplicated / re-imported) count as the same person. */
  characters?: readonly Pick<Character, 'id' | 'name'>[]
  userName?: string
  maxChars?: number
}

export type PastLifeSource = { conversationId: string; title: string; kind: string; chars: number; source: 'memory' | 'summary' | 'excerpt' | 'card' }
export type PastLifeResult = { text: string; sources: PastLifeSource[]; characterIds: string[]; relatedConversationCount: number }

const clip = (value: string, max: number) => value.length > max ? `${value.slice(0, Math.max(0, max - 1))}…` : value
const PAST_LIFE_EXCERPT_LINES = 16

/** This card plus any card with exactly the same name (duplicates, re-imports, story copies). */
export function characterAliasIds(character: Pick<Character, 'id' | 'name'>, characters: readonly Pick<Character, 'id' | 'name'>[] = []) {
  const name = character.name.trim()
  return [...new Set([character.id, ...(name ? characters.filter((item) => item.name.trim() === name).map((item) => item.id) : [])])]
}

/**
 * Does this conversation hold any of the character's life? Covers single story chats
 * (characterId), groups / phone groups / phone DMs (participantIds), members who
 * left a phone group (phone.left), and any message he actually spoke (characterId on the message).
 */
export function conversationInvolvesCharacter(conversation: Conversation, ids: readonly string[]) {
  const has = (id: string | undefined) => Boolean(id && ids.includes(id))
  if (conversation.kind === 'group') {
    if (conversation.participantIds?.length ? conversation.participantIds.some(has) : has(conversation.characterId)) return true
  } else if (has(conversation.characterId)) return true
  if (Object.keys(conversation.phone?.left || {}).some(has)) return true
  if (Object.keys(conversation.characterMemories || {}).some((id) => has(id) && (conversation.characterMemories?.[id]?.length || 0) > 0)) return true
  return conversation.messages.some((message) => message.role === 'assistant' && has(message.characterId))
}

const conversationKind = (conversation: Conversation) => conversation.phone ? (conversation.phone.dm ? '小手机私聊' : '小手机群聊') : conversation.kind === 'group' ? '长剧情·群戏' : '长剧情'

function messageText(text: string) {
  return stripUiOnlyStatusBlocks(stripPresentationalHtmlForPrompt(text)).replace(/\n{2,}/g, '\n').trim()
}

/** His own lines and hers, newest last — for conversations that have no memory or summary yet. */
function conversationExcerpt(conversation: Conversation, ids: readonly string[], name: string, userName: string) {
  const single = conversation.kind !== 'group'
  const lines = conversation.messages
    .filter((message) => !message.phoneNotice && message.text?.trim())
    .filter((message) => message.role === 'user' || (message.characterId ? ids.includes(message.characterId) : single || conversation.phone?.dm))
    .slice(-PAST_LIFE_EXCERPT_LINES)
    .map((message) => `${message.role === 'user' ? userName : name}：${clip(messageText(message.text), 220)}`)
    .filter((line) => !/：$/.test(line))
  return lines.join('\n')
}

/**
 * 前世记忆：这个角色在小手机与长剧情里真实经历过的事 —— 他自己的过去。
 * Newest conversations first, capped. Pure and read-only: never mutates its inputs and only
 * reads conversations this character is in, and inside a shared group only his own memories.
 */
export function collectPastLifeMemory({ character, conversations, memoryEntries, characters = [], userName = '她', maxChars = PAST_LIFE_MAX_CHARS }: PastLifeInput): PastLifeResult {
  const ids = characterAliasIds(character, characters)
  const related = conversations
    .filter((conversation) => conversationInvolvesCharacter(conversation, ids))
    .slice()
    .sort((left, right) => (right.updatedAt || 0) - (left.updatedAt || 0))
  const relatedIds = new Set(related.map((conversation) => conversation.id))
  const blocks: string[] = []
  const sources: PastLifeSource[] = []
  let used = 0
  const push = (block: string, source: Omit<PastLifeSource, 'chars'>) => {
    if (used >= maxChars) return false
    const room = maxChars - used
    const piece = block.length > room ? (room > 200 ? clip(block, room) : '') : block
    if (!piece) { used = maxChars; return false }
    blocks.push(piece)
    used += piece.length + 2
    sources.push({ ...source, chars: piece.length })
    return true
  }
  const memoryLine = (entry: CharacterMemoryEntry) => `· ${entry.title ? `${entry.title}：` : ''}${stripUiOnlyStatusBlocks(entry.content).trim()}`
  const usable = (entry: CharacterMemoryEntry) => entry.enabled !== false && entry.status !== 'superseded' && Boolean(entry.content?.trim())

  // Card-level 角色记忆 is his own memory too (hand-written or not yet migrated to a chat).
  const cardEntries = (character.characterMemory || []).filter(usable).filter((entry) => {
    const source = typeof entry.sourceMemoryId === 'string' ? entry.sourceMemoryId : ''
    return ![...relatedIds].some((id) => source.startsWith(`memory-scan-${id}-`))
  })
  if (cardEntries.length) push(clip(`〔角色卡记忆〕\n${cardEntries.map(memoryLine).join('\n')}`, PAST_LIFE_PER_CONVERSATION), { conversationId: '', title: '角色卡记忆', kind: '角色卡', source: 'card' })

  for (const conversation of related) {
    if (used >= maxChars) break
    const revision = conversation.historyRevision || 0
    const own = ids.flatMap((id) => conversation.characterMemories?.[id] || [])
    const legacy = (character.characterMemory || []).filter((entry) => typeof entry.sourceMemoryId === 'string' && entry.sourceMemoryId.startsWith(`memory-scan-${conversation.id}-`))
    const core = [...own, ...legacy].filter(usable).map(memoryLine)
    // Only this conversation's own key: the legacy per-character fallback would
    // repeat the same old block under every conversation.
    const longEntries = (memoryEntries[conversation.id] || []).filter((entry) => (entry.historyRevision || 0) === revision && entry.content?.trim())
    const long = [...longEntries.filter((entry) => entry.pinned), ...longEntries.filter((entry) => !entry.pinned).slice(-5)]
      .map((entry) => `· ${stripUiOnlyStatusBlocks(entry.content).trim()}`)
    const summary = conversation.contextSummary && (conversation.contextSummaryRevision || 0) === revision ? stripUiOnlyStatusBlocks(conversation.contextSummary).trim() : ''
    const remembered = core.length + long.length
    const excerpt = remembered ? '' : conversationExcerpt(conversation, ids, character.name, userName)
    const parts = [
      core.length ? `他记得的事：\n${core.join('\n')}` : '',
      long.length ? `那段日子：\n${long.join('\n')}` : '',
      summary && remembered < 4 ? `经过：\n${clip(summary, 1200)}` : '',
      excerpt && !summary ? `最后聊到的：\n${excerpt}` : excerpt ? `最后聊到的：\n${excerpt.split('\n').slice(-6).join('\n')}` : '',
    ].filter(Boolean)
    if (!parts.length) continue
    const kind = conversationKind(conversation)
    const block = clip(`〔${kind}｜${conversation.title || '未命名'}〕\n${parts.join('\n')}`, PAST_LIFE_PER_CONVERSATION)
    push(block, { conversationId: conversation.id, title: conversation.title || '未命名', kind, source: remembered ? 'memory' : summary ? 'summary' : 'excerpt' })
  }
  if (!blocks.length) return { text: '', sources, characterIds: ids, relatedConversationCount: related.length }
  const text = `【${character.name}的前世记忆｜他亲身经历过的过去，只读】
下面是 ${character.name} 自己在小手机日常与长剧情故事里，和{{user}}一起真实经历过的事。这是他的过去 —— 他和{{user}}这段缘分更早的篇章，他记得，是他的一部分。
- 用第一人称的“记得”去用它：熟悉她的习惯、记得一起经历的事、延续当时的情感与称呼，自然地流露在言行细节里；她问起时可以坦然说记得。
- 那些故事里的地点、身份和未完的事件属于过去的篇章，不要当成此刻正在发生；不要逐条复述，不要说“资料显示”“记录里写着”。
- 与这扇窗口自己的记忆或最新对话冲突时，以这扇窗口为准。

${blocks.join('\n\n')}`
  return { text, sources, characterIds: ids, relatedConversationCount: related.length }
}

export function buildPastLifeMemory(input: PastLifeInput) {
  return collectPastLifeMemory(input).text
}

const UI_LORE = /(<\/?(?:div|span|status|style|section|details|table)\b|状态栏|美化|输出格式|格式要求|html|css|正则)/i
/** 世界书里人设条目的总预算：超出部分仍按关键词触发。 */
export const PERSONA_WORLDBOOK_BUDGET = 12000

/**
 * The persona window has almost no chat to scan, so keyword-triggered card lore
 * (where many cards keep the real 人设) would never fire. Promote the card's own
 * setting entries to always-on, within a budget; skip display/status-bar lore.
 */
export function personaWorldbook(book: CharacterBook | undefined, budget = PERSONA_WORLDBOOK_BUDGET): CharacterBook | undefined {
  if (!book?.entries?.length) return book
  let used = 0
  const entries = book.entries.slice().sort((a, b) => a.insertion_order - b.insertion_order).flatMap((entry) => {
    if (!entry.enabled || !entry.content.trim()) return [entry]
    if (UI_LORE.test(entry.content) || UI_LORE.test(entry.comment || '')) return entry.constant ? [] : [entry]
    const depth = Number(entry.extensions?.position) === 4 || entry.position === 'at_depth'
    if (depth) return [entry]
    if (entry.constant) { used += entry.content.length; return [entry] }
    if (used + entry.content.length > budget) return [entry]
    used += entry.content.length
    return [{ ...entry, constant: true, selective: false, extensions: { ...entry.extensions, useProbability: false } }]
  })
  return { ...book, entries }
}

