/**
 * 人格窗口：每个被启用的角色都有一扇属于“他自己”的独立窗口。
 *
 * - 窗口里的对话不是故事会话：它不进 weijing.conversations，因此不会出现在
 *   聊天列表、聊天搜索、小手机或剧本项目里，也不会被那些地方的记忆总结读到。
 * - 每个人格有自己的长期记忆（按人格 id 存放），与其他人格、与长剧情/小手机的
 *   记忆完全隔离；人格窗口永远不会把记忆写回那些会话。
 * - 「前世记忆」只读：从同一角色在小手机与长剧情里已有的记忆/摘要拼出一段
 *   有上限的参考资料，单独标注后注入。
 */
import type { Character, CharacterMemoryEntry } from './characterCard'
import type { ChatImage } from './chatImages'
import type { Conversation } from './conversationLifecycle'
import type { LongMemoryEntry, LongMemoryMap } from './memoryEngine'
import { conversationHasCharacter, memoriesForConversationCharacter } from './conversationCharacterMemory'
import { stripUiOnlyStatusBlocks } from './modelContext'

export const PERSONA_WINDOWS_KEY = 'weijing.personaWindows'
/** 自动整理记忆：攒够这么多条新消息（用户 + 角色）就后台整理一次。 */
export const PERSONA_MEMORY_EVERY = 12
/** 单次整理最多读这么多条，剩下的留给下一次。 */
export const PERSONA_MEMORY_BATCH = 60
export const PERSONA_MEMORY_LIMIT = 300
export const PAST_LIFE_MAX_CHARS = 6000
const PAST_LIFE_PER_CONVERSATION = 1800

export type PersonaMessage = {
  id: number
  role: 'user' | 'assistant'
  text: string
  images?: ChatImage[]
  createdAt: number
  finishReason?: string | null
}

export type PersonaMemoryEntry = {
  id: string
  title: string
  content: string
  createdAt: number
  updatedAt?: number
  pinned?: boolean
  autoGenerated?: boolean
}

export type PersonaWindow = {
  /** 人格 id（记忆按它隔离），与 characterId 一一对应。 */
  id: string
  characterId: string
  createdAt: number
  updatedAt: number
  /** 移出窗口时只隐藏，不删除对话和记忆；重新加入即可恢复。 */
  enabled: boolean
  messages: PersonaMessage[]
  memories: PersonaMemoryEntry[]
  /** 已整理进长期记忆的最后一条消息 id。 */
  memoryThroughId?: number
  /** 自动整理记忆，默认开。 */
  autoMemory?: boolean
  /** 前世记忆（小手机 + 长剧情）只读注入，默认开。 */
  pastLifeEnabled?: boolean
  /** 较早对话的压缩摘要；只影响请求，不改原文。 */
  contextSummary?: string
  /** 摘要覆盖到的最后一条消息 id（用 id 而非下标，删消息也不会错位）。 */
  compressedThroughId?: number
}

export type PersonaWindowState = { version: 1; activeId: string; personas: PersonaWindow[] }

export const emptyPersonaState = (): PersonaWindowState => ({ version: 1, activeId: '', personas: [] })

export const personaIdFor = (characterId: string) => `persona-${characterId}`

const isRecord = (value: unknown): value is Record<string, unknown> => Boolean(value) && typeof value === 'object' && !Array.isArray(value)
const text = (value: unknown) => typeof value === 'string' ? value : ''

function normalizeMessage(value: unknown): PersonaMessage | null {
  if (!isRecord(value)) return null
  const id = Number(value.id)
  const role = value.role === 'user' ? 'user' : value.role === 'assistant' ? 'assistant' : null
  if (!Number.isFinite(id) || !role) return null
  const images = Array.isArray(value.images) ? (value.images as ChatImage[]).filter((image) => image && typeof image.dataUrl === 'string') : undefined
  return { id, role, text: text(value.text), createdAt: Number(value.createdAt) || 0, ...(images?.length ? { images } : {}), ...(value.finishReason !== undefined ? { finishReason: (value.finishReason as string | null) } : {}) }
}

function normalizeMemory(value: unknown): PersonaMemoryEntry | null {
  if (!isRecord(value)) return null
  const content = text(value.content).trim()
  if (!content) return null
  return {
    id: text(value.id) || crypto.randomUUID(),
    title: text(value.title).trim() || '记忆',
    content,
    createdAt: Number(value.createdAt) || 0,
    ...(value.updatedAt ? { updatedAt: Number(value.updatedAt) || 0 } : {}),
    ...(value.pinned ? { pinned: true } : {}),
    ...(value.autoGenerated ? { autoGenerated: true } : {}),
  }
}

export function normalizePersonaState(value: unknown): PersonaWindowState {
  if (!isRecord(value) || !Array.isArray(value.personas)) return emptyPersonaState()
  const seen = new Set<string>()
  const personas: PersonaWindow[] = []
  for (const raw of value.personas) {
    if (!isRecord(raw)) continue
    const characterId = text(raw.characterId)
    if (!characterId) continue
    const id = text(raw.id) || personaIdFor(characterId)
    if (seen.has(id)) continue
    seen.add(id)
    personas.push({
      id,
      characterId,
      createdAt: Number(raw.createdAt) || 0,
      updatedAt: Number(raw.updatedAt) || 0,
      enabled: raw.enabled !== false,
      messages: (Array.isArray(raw.messages) ? raw.messages : []).map(normalizeMessage).filter((item): item is PersonaMessage => Boolean(item)),
      memories: (Array.isArray(raw.memories) ? raw.memories : []).map(normalizeMemory).filter((item): item is PersonaMemoryEntry => Boolean(item)),
      ...(Number.isFinite(Number(raw.memoryThroughId)) && raw.memoryThroughId !== undefined ? { memoryThroughId: Number(raw.memoryThroughId) } : {}),
      autoMemory: raw.autoMemory !== false,
      pastLifeEnabled: raw.pastLifeEnabled !== false,
      ...(text(raw.contextSummary) ? { contextSummary: text(raw.contextSummary) } : {}),
      ...(Number.isFinite(Number(raw.compressedThroughId)) && raw.compressedThroughId !== undefined ? { compressedThroughId: Number(raw.compressedThroughId) } : {}),
    })
  }
  const activeId = text(value.activeId)
  return { version: 1, activeId: personas.some((item) => item.id === activeId && item.enabled) ? activeId : personas.find((item) => item.enabled)?.id || '', personas }
}

export function createPersonaWindow(characterId: string, now = Date.now()): PersonaWindow {
  return { id: personaIdFor(characterId), characterId, createdAt: now, updatedAt: now, enabled: true, messages: [], memories: [], autoMemory: true, pastLifeEnabled: true }
}

/** Enable a character as a persona. A previously removed persona comes back with its own chat and memory intact. */
export function enablePersona(state: PersonaWindowState, characterId: string, now = Date.now()): PersonaWindowState {
  const existing = state.personas.find((item) => item.characterId === characterId)
  if (existing) {
    return { ...state, activeId: existing.id, personas: state.personas.map((item) => item.id === existing.id ? { ...item, enabled: true } : item) }
  }
  const persona = createPersonaWindow(characterId, now)
  return { ...state, activeId: persona.id, personas: [...state.personas, persona] }
}

/** Hide a persona from the window. Its chat and memory are kept for when it is added back. */
export function disablePersona(state: PersonaWindowState, personaId: string): PersonaWindowState {
  const personas = state.personas.map((item) => item.id === personaId ? { ...item, enabled: false } : item)
  const activeId = state.activeId === personaId ? personas.find((item) => item.enabled)?.id || '' : state.activeId
  return { ...state, activeId, personas }
}

/** Permanently delete one persona's chat and memory. Other personas are untouched. */
export function deletePersona(state: PersonaWindowState, personaId: string): PersonaWindowState {
  const personas = state.personas.filter((item) => item.id !== personaId)
  const activeId = state.activeId === personaId ? personas.find((item) => item.enabled)?.id || '' : state.activeId
  return { ...state, activeId, personas }
}

export function switchPersona(state: PersonaWindowState, personaId: string): PersonaWindowState {
  return state.personas.some((item) => item.id === personaId && item.enabled) ? { ...state, activeId: personaId } : state
}

export function updatePersona(state: PersonaWindowState, personaId: string, transform: (persona: PersonaWindow) => PersonaWindow): PersonaWindowState {
  let changed = false
  const personas = state.personas.map((item) => {
    if (item.id !== personaId) return item
    changed = true
    return transform(item)
  })
  return changed ? { ...state, personas } : state
}

export const nextPersonaMessageId = (messages: PersonaMessage[]) => messages.reduce((max, item) => Math.max(max, item.id), 0) + 1

/** Memory reads and writes are always keyed by persona id; nothing here can reach another persona. */
export function personaMemories(state: PersonaWindowState, personaId: string) {
  return state.personas.find((item) => item.id === personaId)?.memories || []
}

const normalizedMemoryText = (value: string) => value.toLocaleLowerCase().replace(/[\s，。！？；：、“”‘’"'（）()【】［］《》<>…,.!?;:/\\|·]/g, '')

export function mergePersonaMemories(existing: PersonaMemoryEntry[], incoming: PersonaMemoryEntry[], limit = PERSONA_MEMORY_LIMIT) {
  const merged = existing.slice()
  for (const candidate of incoming) {
    const key = normalizedMemoryText(candidate.content)
    const titleKey = normalizedMemoryText(candidate.title)
    const index = merged.findIndex((item) => normalizedMemoryText(item.content) === key || (titleKey.length >= 4 && normalizedMemoryText(item.title) === titleKey))
    if (index < 0) { merged.push(candidate); continue }
    const previous = merged[index]
    // A hand-edited memory is hers: an automatic pass never overwrites it.
    if (previous.autoGenerated === true && normalizedMemoryText(previous.content) !== key) merged[index] = { ...previous, content: candidate.content, title: candidate.title, updatedAt: candidate.createdAt }
  }
  const pinned = merged.filter((item) => item.pinned)
  const ordinary = merged.filter((item) => !item.pinned)
  return [...pinned, ...ordinary.slice(-Math.max(0, limit - pinned.length))]
}

/** Write auto-extracted memories into exactly one persona and advance only its cursor. */
export function applyPersonaMemoryExtraction(state: PersonaWindowState, personaId: string, incoming: PersonaMemoryEntry[], throughId: number): PersonaWindowState {
  return updatePersona(state, personaId, (persona) => ({
    ...persona,
    memories: mergePersonaMemories(persona.memories, incoming),
    memoryThroughId: Math.max(persona.memoryThroughId || 0, throughId),
  }))
}

export function pendingPersonaMemoryMessages(persona: PersonaWindow) {
  const through = persona.memoryThroughId || 0
  return persona.messages.filter((item) => item.id > through && item.text.trim() && !(item.role === 'assistant' && item.finishReason === 'error'))
}

export function shouldExtractPersonaMemory(persona: PersonaWindow, every = PERSONA_MEMORY_EVERY) {
  return persona.autoMemory !== false && pendingPersonaMemoryMessages(persona).length >= every
}

