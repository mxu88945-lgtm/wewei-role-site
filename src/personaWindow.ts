function jsonCandidates(raw: string) {
  const cleaned = raw.replace(/^\s*```(?:json)?\s*/i, '').replace(/\s*```\s*$/i, '').trim()
  const candidates = [cleaned]
  const start = cleaned.indexOf('{')
  const end = cleaned.lastIndexOf('}')
  if (start >= 0 && end > start) candidates.push(cleaned.slice(start, end + 1))
  const arrayStart = cleaned.indexOf('[')
  const arrayEnd = cleaned.lastIndexOf(']')
  if (arrayStart >= 0 && arrayEnd > arrayStart) candidates.push(cleaned.slice(arrayStart, arrayEnd + 1))
  return candidates
}

export function parsePersonaMemoryCandidates(raw: string, now = Date.now()): PersonaMemoryEntry[] | null {
  for (const candidate of jsonCandidates(raw)) {
    let parsed: unknown
    try { parsed = JSON.parse(candidate) } catch { continue }
    const items = Array.isArray(parsed) ? parsed : isRecord(parsed) && Array.isArray(parsed.memories) ? parsed.memories : null
    if (!items) continue
    const seen = new Set<string>()
    const entries: PersonaMemoryEntry[] = []
    for (const item of items) {
      if (!isRecord(item)) continue
      const content = stripUiOnlyStatusBlocks(text(item.content || item.summary || item.fact)).trim().slice(0, 1200)
      const title = text(item.title || item.name).trim().slice(0, 80) || content.slice(0, 16)
      const key = normalizedMemoryText(content)
      if (!content || seen.has(key)) continue
      seen.add(key)
      entries.push({ id: crypto.randomUUID(), title, content, createdAt: now, autoGenerated: true })
    }
    return entries
  }
  return null
}

