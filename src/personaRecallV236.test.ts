describe('线索、重要度、用进废退 (v236)', () => {
  it('old memories without the new fields still work: cues and importance are estimated, nothing is written back', () => {
    const state = normalizePersonaState({ personas: [{ characterId: 'yu', memories: [{ id: 'a', title: '生日', content: '她的生日是三月五日，他答应那天陪她看日出。' }] }] })
    const entry = state.personas[0].memories[0]
    expect(entry).not.toHaveProperty('cues')
    expect(entry).not.toHaveProperty('importance')
    expect(entry).not.toHaveProperty('recallCount')
    expect(memoryCues(entry)).toContain('生日')
    expect(memoryImportance(entry)).toBe(5) // 承诺/生日 4，她手写 +1
    expect(memoryImportance({ ...entry, autoGenerated: true })).toBe(4)
    expect(memoryImportance({ title: '天气', content: '今天下雨', autoGenerated: true })).toBe(2)
  })

  it('new fields round-trip; bad values are dropped', () => {
    const state = normalizePersonaState({ personas: [{ characterId: 'yu', memories: [
      { id: 'a', title: 't', content: 'c', cues: ['小鸡', '小鸡', 'x', 3], importance: 9, lastRecalledAt: 123, recallCount: 2 },
      { id: 'b', title: 't', content: 'd', cues: 'nope', importance: 'high', lastRecalledAt: -1, recallCount: 1.5 },
    ] }] })
    const [a, b] = state.personas[0].memories
    expect(a).toMatchObject({ cues: ['小鸡'], importance: 5, lastRecalledAt: 123, recallCount: 2 })
    expect(Object.keys(b).sort()).toEqual(['content', 'createdAt', 'id', 'title'])
  })

  it('the memory organizer can return cues and importance (gist entries)', () => {
    const [entry] = parsePersonaMemoryCandidates('{"memories":[{"title":"和好","content":"十月中旬闹别扭后和好，约好每晚说晚安。","cues":["晚安","闹别扭","和好"],"importance":5}]}', 1)!
    expect(entry).toMatchObject({ cues: ['晚安', '闹别扭', '和好'], importance: 5, autoGenerated: true })
  })

  it('cue scan is only her latest message + his previous reply', () => {
    const history = [say(1, 'user', '很久以前聊过团子'), say(2, 'assistant', '嗯，小鸡今天乖吗'), say(3, 'user', '今天好累')]
    expect(cueScanText(history)).toBe('嗯，小鸡今天乖吗\n今天好累')
    expect(cueHits(['团子'], cueScanText(history))).toBe(0)
    expect(cueHits(['鹦鹉'], '小鸡今天乖', [['鹦鹉', '小鸡']])).toBe(1)
  })

  it('forgetting curve: fades slowly, never below the floor; each recall refreshes and slows the fade', () => {
    const old = mem('a', 'x', 'y', { createdAt: FIXTURE_NOW - 30 * DAY })
    expect(memoryFreshness(old, FIXTURE_NOW)).toBeCloseTo(MEMORY_FRESHNESS_FLOOR + (1 - MEMORY_FRESHNESS_FLOOR) / 2, 5)
    expect(memoryFreshness({ ...old, createdAt: FIXTURE_NOW - 3000 * DAY }, FIXTURE_NOW)).toBeGreaterThanOrEqual(MEMORY_FRESHNESS_FLOOR)
    const [touched] = touchRecalledMemories([old], ['a'], FIXTURE_NOW)
    expect(touched).toMatchObject({ lastRecalledAt: FIXTURE_NOW, recallCount: 1 })
    expect(memoryFreshness(touched, FIXTURE_NOW)).toBe(1)
    const later = FIXTURE_NOW + 30 * DAY
    expect(memoryFreshness(touched, later)).toBeGreaterThan(memoryFreshness({ ...old, createdAt: FIXTURE_NOW }, later))
    expect(touchRecalledMemories([old], [], FIXTURE_NOW)[0]).toBe(old)
  })

  it('ranking = relevance × importance × freshness: a promise outranks small talk on the same cue', () => {
    const small = mem('s', '茶', '她今天喝了一杯茶。', { cues: ['喝茶'], importance: 1 })
    const promise = mem('p', '茶', '他答应以后每天提醒她喝茶也喝水。', { cues: ['喝茶'], importance: 5 })
    const faded = mem('f', '茶', '很久以前她说过喜欢红茶。', { cues: ['喝茶'], importance: 5, createdAt: FIXTURE_NOW - 400 * DAY })
    const ranked = rankPersonaMemories([small, faded, promise], { scan: '我在喝茶', now: FIXTURE_NOW })
    // 很久（400 天）没被想起的会慢慢沉下去，但不会消失；同样新鲜时重要的排前面。
    expect(ranked.map((row) => row.entry.id)).toEqual(['p', 's', 'f'])
    const ancient = (entry: PersonaMemoryEntry) => ({ ...entry, createdAt: FIXTURE_NOW - 400 * DAY })
    expect(rankPersonaMemories([ancient(small), ancient(promise)], { scan: '我在喝茶', now: FIXTURE_NOW }).map((row) => row.entry.id)).toEqual(['p', 's'])
    expect(rankPersonaMemories([small], { scan: '今天好累', now: FIXTURE_NOW })).toEqual([])
  })

  it('semantic hits pull a memory even with no shared words; without semantic, weak keyword overlap does not', () => {
    const entry = mem('m', '团子', '她小时候养过一只橘猫叫团子。')
    expect(rankPersonaMemories([entry], { scan: '最近好想养只猫', semantic: new Map([['m', .7]]), now: FIXTURE_NOW })[0]?.via).toBe('semantic')
    expect(rankPersonaMemories([entry], { scan: '最近好想养只猫', keywordScore: () => 1, now: FIXTURE_NOW })).toEqual([])
    expect(rankPersonaMemories([entry], { scan: '最近好想养只猫', keywordScore: () => 6, now: FIXTURE_NOW })).toHaveLength(1)
  })
})

describe('按需注入 (v236)', () => {
  const make = (memories: PersonaMemoryEntry[], messages: PersonaMessage[]) => {
    const persona: PersonaWindow = { ...createPersonaWindow('yu', 1), memories }
    const thread = { ...activeThread(persona), messages }
    return { persona: { ...persona, threads: [thread] }, thread }
  }

  it('small talk recalls no long-term memory; naming a cue pulls only that memory body into the turn', () => {
    const memories = [mem('a', '小鸡尿垫', '她每天早上给九只小鸡换尿垫。', { cues: ['小鸡', '尿垫'] }), mem('b', '唱歌', '她周末爱去KTV唱粤语歌。', { cues: ['唱歌', 'KTV'] })]
    const casual = [say(1, 'user', '今天好累，晚上随便吃了点东西')]
    let { persona, thread } = make(memories, casual)
    let ctx = buildPersonaMemoryContext(persona, thread, casual, casual, names, FIXTURE_NOW)
    expect(ctx.dynamicText).not.toContain('尿垫')
    expect(ctx.recalledMemoryIds).toEqual([])
    const asked = [say(1, 'user', '小鸡今天又把尿垫叼走了')]
    ;({ persona, thread } = make(memories, asked))
    ctx = buildPersonaMemoryContext(persona, thread, asked, asked, names, FIXTURE_NOW)
    expect(ctx.dynamicText).toContain('九只小鸡换尿垫')
    expect(ctx.dynamicText).not.toContain('粤语歌')
    expect(ctx.recalledMemoryIds).toEqual(['a'])
    expect(ctx.stableText).toBe('')
  })

  it('dedupe: a memory whose body is already in the recent context is not recalled again', () => {
    const memories = [mem('a', '小鸡尿垫', '她每天早上给九只小鸡换尿垫。', { cues: ['小鸡'] })]
    const history = [say(1, 'assistant', '我记得，她每天早上给九只小鸡换尿垫。'), say(2, 'user', '小鸡呢')]
    const { persona, thread } = make(memories, history)
    expect(buildPersonaMemoryContext(persona, thread, history, history, names, FIXTURE_NOW).recalledMemoryIds).toEqual([])
  })

  it('semantic message hits inject an old original even without shared words; it is never one already in context', () => {
    const old = Array.from({ length: 6 }, (_, index) => say(index + 1, index % 2 ? 'assistant' : 'user', index === 2 ? '我小时候养过一只橘猫，叫团子。' : `别的话题${index}`, FIXTURE_NOW - 10 * DAY))
    const latest = say(10, 'user', '最近好想养只猫')
    const history = [...old, latest]
    const { persona, thread } = make([], history)
    const without = buildPersonaMemoryContext(persona, thread, history, [latest], names, FIXTURE_NOW)
    const original = (ctx: typeof without) => ctx.audit.lanes.find((lane) => lane.key === 'original')!.preview
    expect(original(without)).not.toContain('团子')
    const semantic = { messages: new Map([[`${thread.id}|3`, .72], [`${thread.id}|10`, .9]]), memories: new Map(), chunks: new Map() }
    const withHits = buildPersonaMemoryContext(persona, thread, history, [latest], names, FIXTURE_NOW, { semantic })
    expect(original(withHits)).toContain('团子')
    expect(withHits.audit.sources.map((source) => source.messageId)).not.toContain(10)
    expect(withHits.audit.recallMode).toBe('semantic')
  })

  it('the stable first system is byte-identical across turns and topics, with or without semantic hits; recall rides in the tail', () => {
    const persona = fixturePersona()
    const plan = (latest: string, semantic?: Parameters<typeof planPersonaRequest>[4] extends infer O ? O extends { semantic?: infer S } ? S : never : never) => {
      const history = fixtureHistory(latest)
      return planPersonaRequest(persona, history, fixtureDeps(), { ...activeThread(persona), messages: history }, { semantic })
    }
    const casual = plan('今天好累，晚上随便吃了碗面。')
    const asked = plan('你还记得书院群里林栖起哄让你唱歌那次吗？')
    const semantic = plan('想起雪原那封信', { messages: new Map(), memories: new Map([['m12', .8]]), chunks: new Map() })
    expect(systemOf(asked.messages)).toBe(systemOf(casual.messages))
    expect(systemOf(semantic.messages)).toBe(systemOf(casual.messages))
    expect(tailOf(asked.messages)).toContain(TURN_CONTEXT_OPEN)
    expect(tailOf(asked.messages)).toContain('前世记忆·按需召回｜只读')
    expect(systemOf(casual.messages)).not.toContain('前世记忆·按需召回｜只读')
    expect(tailOf(semantic.messages)).toContain('第 12 次提到')
    expect(semantic.memory.recalledMemoryIds).toContain('m12')
    // 召回合计不超过上限
    const recallLanes = ['original', 'facts', 'continuity-related', 'derived', 'past-life', 'background']
    for (const result of [casual, asked, semantic]) {
      const used = result.memory.audit.lanes.filter((lane) => recallLanes.includes(lane.key)).reduce((sum, lane) => sum + lane.chars, 0)
      expect(used).toBeLessThanOrEqual(PERSONA_TURN_RECALL_MAX_CHARS)
    }
  })

  it('typical small-talk request: big story background, non-core lore and old gift history stay out', () => {
    const persona = fixturePersona()
    const history = fixtureHistory('今天好累，晚上随便吃了碗面。')
    const result = planPersonaRequest(persona, history, fixtureDeps(), { ...activeThread(persona), messages: history })
    const all = JSON.stringify(result.messages)
    expect(all).not.toContain('大周王朝末年') // 故事背景（长）只留指路
    expect(all).toContain('故事背景｜按需附上')
    expect(all).not.toContain('朝中太子与三皇子') // 非核心世界书条目
    expect(all).toContain('虞山行十六岁从军') // 他本人的条目常驻
    expect(all).not.toContain('前世记忆·按需召回｜只读')
    expect(result.memory.audit.parts?.find((part) => part.key === 'card-lore')?.chars).toBeGreaterThan(0)
    // 功能说明仍在
    for (const piece of ['[送礼:', '[人物:', '[提醒:', '[点歌:', '[记忆:', '[自我卡:']) expect(all).toContain(piece)
  })
})

