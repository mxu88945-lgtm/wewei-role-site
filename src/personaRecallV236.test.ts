describe('语义召回接线 (v236)', () => {
  class MapStorage implements Storage {
    private data = new Map<string, string>()
    get length() { return this.data.size }
    clear() { this.data.clear() }
    getItem(key: string) { return this.data.get(key) ?? null }
    key(index: number) { return [...this.data.keys()][index] ?? null }
    removeItem(key: string) { this.data.delete(key) }
    setItem(key: string, value: string) { this.data.set(key, String(value)) }
  }
  const channel: ApiChannel = { id: 'sf', name: '硅基流动', platform: 'custom-openai', protocol: 'openai', baseUrl: 'https://api.siliconflow.cn/v1', apiKey: 'sk-test', modelName: 'x', maxTokenField: 'auto' }
  const vec = (text: string) => text.includes('团子') || text.includes('猫') ? [1, 0] : [0, 1]
  const persona = (id: string): PersonaWindow => {
    const base = createPersonaWindow(id, 1)
    const long = '它每天趴在窗台上晒太阳，胖得像个团子。'.repeat(12)
    const messages = [say(1, 'user', `我小时候养过一只橘猫，叫团子。${long}`), say(2, 'assistant', `团子一定很可爱。${long}`), say(3, 'user', '今天好累'), say(4, 'assistant', '早点睡')]
    return { ...base, threads: [{ ...base.threads[0], messages }], memories: [mem(`${id}-m`, '团子', '她小时候养过橘猫团子。'), mem(`${id}-n`, '茶', '她每天喝茶。')] }
  }

  it('only this persona: its windows and its memories, never another persona; off = null with no request', async () => {
    vi.useRealTimers()
    Object.defineProperty(globalThis, 'localStorage', { value: new MapStorage(), configurable: true })
    const mine = persona('yu'), other = persona('lin')
    const records: VectorRecord[] = personaSegments([mine, other], 'BAAI/bge-m3').map((segment) => ({ key: segment.key, model: 'BAAI/bge-m3', conversationId: segment.conversationId, dim: 2, vec: normalize(vec(segment.text)), text: segment.text, msgIds: segment.msgIds, createdAt: 1 }))
    expect(new Set(records.map((record) => record.conversationId))).toEqual(new Set([`persona:${mine.threads[0].id}`, `persona-mem:${mine.id}`, `persona:${other.threads[0].id}`, `persona-mem:${other.id}`]))
    const store: VectorStore = { keys: async () => new Set(records.map((r) => r.key)), forConversation: async (model, id) => records.filter((r) => r.model === model && r.conversationId === id), put: async () => {}, remove: async () => {}, clear: async () => {} }
    const fetchMock = vi.fn(async (_url: string, init: RequestInit) => { const body = JSON.parse(String(init.body)) as { input: string[] }; return new Response(JSON.stringify({ data: body.input.map((text, index) => ({ index, embedding: vec(text) })) }), { status: 200 }) })
    vi.stubGlobal('fetch', fetchMock)
    resetSemanticRuntimeForTest(store)
    registerSemanticSources({ conversations: () => [], channels: () => [channel] })
    const pools = { pastLife: null, background: [], setting: '', globalWorldbook: '', backgroundTitles: [] }
    const input = { persona: mine, thread: mine.threads[0], history: mine.threads[0].messages, pools, inContextKeys: new Set([`${mine.threads[0].id}|3`, `${mine.threads[0].id}|4`]), query: '想再养一只猫' }
    expect(await semanticRecallForPersona(input)).toBeNull()
    expect(fetchMock).not.toHaveBeenCalled()
    updateSemanticConfig({ enabled: true })
    const hits = (await semanticRecallForPersona(input))!
    expect([...hits.memories.keys()]).toEqual(['yu-m'])
    expect([...hits.messages.keys()].sort()).toEqual([`${mine.threads[0].id}|1`, `${mine.threads[0].id}|2`])
    expect(JSON.stringify([...hits.messages.keys(), ...hits.memories.keys()])).not.toContain('lin')
    resetSemanticRuntimeForTest()
  })
})

