const BASELINE = 0.5

export function fakeEmbed(text: string): number[] {
  return [BASELINE, ...TOPICS.map((words) => words.some((word) => text.includes(word)) ? 1 : 0)]
}

export function fakeCosine(a: string, b: string) {
  const x = fakeEmbed(a), y = fakeEmbed(b)
  const dot = x.reduce((sum, value, index) => sum + value * y[index], 0)
  const norm = (v: number[]) => Math.sqrt(v.reduce((sum, value) => sum + value * value, 0))
  return dot / (norm(x) * norm(y))
}
